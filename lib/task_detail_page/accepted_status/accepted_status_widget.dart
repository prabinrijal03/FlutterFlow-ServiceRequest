  Future<void> fetchData() async {
    setState(() {
      _model.isLoading = true;
      _model.errorMessage = null;
    });

    try {
      // Step 1: Get user info
      _model.userInfoResponse = await GetUserInfoCall.call(
        bearerToken: FFAppState().BearerToken,
      );

      if (!(_model.userInfoResponse?.succeeded ?? false)) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage = 'Failed to get user info';
        });
        return;
      }

      final aidboxId =
          GetUserInfoCall.aidboxId(_model.userInfoResponse?.jsonBody);
      if (aidboxId == null) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage = 'Aidbox ID not found in user info';
        });
        return;
      }

      // Step 2: Get user details
      _model.userDetailsResponse = await GetUserDetailsCall.call(
        aidboxId: aidboxId,
        bearerToken: FFAppState().BearerToken,
      );

      // Step 3: Get service requests
      _model.serviceRequestsResponse = await GetServiceRequestsCall.call(
        bearerToken: FFAppState().BearerToken,
      );

      if (!(_model.serviceRequestsResponse?.succeeded ?? false)) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage = 'Failed to get service requests';
        });
        return;
      }

      final entries = GetServiceRequestsCall.entries(
          _model.serviceRequestsResponse?.jsonBody);
      if (entries == null || entries.isEmpty) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage = 'No service requests found';
        });
        return;
      }

      // Get the first service request
      final serviceRequest = entries.first;

      // Extract patient reference
      final patientReference =
          GetServiceRequestsCall.patientReference(serviceRequest);
      if (patientReference == null) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage =
              'Patient reference not found in service request';
        });
        return;
      }

      // Extract patient ID from reference (format: "Patient/123")
      final patientId = patientReference.toString().split('/').last;

      // Step 4: Get patient details
      _model.patientDetailsResponse = await GetPatientDetailsCall.call(
        patientId: patientId,
        bearerToken: FFAppState().BearerToken,
      );

      if (!(_model.patientDetailsResponse?.succeeded ?? false)) {
        setState(() {
          _model.isLoading = false;
          _model.errorMessage = 'Failed to get patient details';
        });
        return;
      }

      // Update form fields with patient data
      final patientName = GetPatientDetailsCall.patientName(
          _model.patientDetailsResponse?.jsonBody);
      final birthDate = GetPatientDetailsCall.birthDate(
          _model.patientDetailsResponse?.jsonBody);
      final gender =
          GetPatientDetailsCall.gender(_model.patientDetailsResponse?.jsonBody);
      final address = GetPatientDetailsCall.address(
          _model.patientDetailsResponse?.jsonBody);

      // Update form fields with service request data
      final bloodPressure =
          GetServiceRequestsCall.bloodPressure(serviceRequest);
      final height = GetServiceRequestsCall.height(serviceRequest);
      final weight = GetServiceRequestsCall.weight(serviceRequest);
      final insuranceProvider =
          GetServiceRequestsCall.insuranceProvider(serviceRequest);
      final policyNumber = GetServiceRequestsCall.policyNumber(serviceRequest);

      // Calculate age from birth date if available
      String age = '';
      if (birthDate != null) {
        final birthDateTime = DateTime.tryParse(birthDate);
        if (birthDateTime != null) {
          final now = DateTime.now();
          age = (now.year - birthDateTime.year).toString();
          if (now.month < birthDateTime.month ||
              (now.month == birthDateTime.month &&
                  now.day < birthDateTime.day)) {
            age = (int.parse(age) - 1).toString();
          }
        }
      }

      // Update text controllers
      setState(() {
        _model.textController1.text = patientName ?? 'Unknown';
        _model.textController2.text = birthDate ?? '';
        _model.textController3.text = age;
        _model.textController12.text = gender ?? 'Unknown';
        _model.textController4.text = bloodPressure ?? '';
        _model.textController5.text = height ?? '';
        _model.textController6.text = weight ?? '';
        _model.textController7.text = insuranceProvider ?? '';
        _model.textController8.text = policyNumber ?? '';
        _model.textController9.text = address ?? '';
        _model.textController10.text = 'Medical consultation and evaluation';
        _model.textController11.text = 'Dr. Elizabeth Johnson';
        _model.isLoading = false;
      });
    } catch (e) {
      print('Error fetching data: $e');
      setState(() {
        _model.isLoading = false;
        _model.errorMessage = 'Error fetching data: $e';
      });
    }
  }

